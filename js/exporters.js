  function questGuide(P) {
    let s = `# ${P.meta.name} - quest guide\n\n_Generated by DayZ Studio._\n\n`;
    P.quests.forEach((q) => {
      s += `## ${q.name}\n${q.description ? q.description + '\n' : ''}\n`;
      if (q.repeatable) s += `* Repeatable (cooldown ${q.cooldown}s of play time)\n`;
      if (q.failOnDeath) s += '* Restarts if the player dies\n';
      const req = (q.requires || []).map((id) => P.quests.find((x) => x.id === id)).filter(Boolean);
      if (req.length) s += `* Unlocks after: ${req.map((x) => x.name).join(', ')}\n`;
      const order = [];
      const seen = new Set();
      const visit = (id) => {
        if (seen.has(id)) return;
        seen.add(id);
        const n = S.node(q, id);
        if (!n) return;
        order.push(n);
        q.links.filter((l) => l.from === id).forEach((l) => visit(l.to));
      };
      q.nodes.filter((n) => DS.NODE_TYPES[n.type].cat === 'trigger').forEach((n) => visit(n.id));
      order.forEach((n, i) => {
        const T = DS.NODE_TYPES[n.type];
        s += `${i + 1}. **${T.title}** - ${T.sum ? T.sum(n.p) : ''}\n`;
      });
      s += '\n';
    });
    return s;
  }

